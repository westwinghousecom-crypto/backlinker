// Copies docs/legal/*.md into src/features/legal/documents.ts so the public /privacy and /terms pages always show the
// reviewed documents. Run `npm run sync:legal` after editing the markdown. A test fails if the two ever drift apart.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const docs = path.resolve(here, "../../docs/legal");
const out = path.resolve(here, "../src/features/legal/documents.ts");

const read = (name) => fs.readFileSync(path.join(docs, name), "utf8").replace(/\r\n/g, "\n");
const body =
  "// GENERATED by scripts/sync-legal.mjs from docs/legal/*.md. Do not edit by hand.\n" +
  `export const PRIVACY_POLICY_MD = ${JSON.stringify(read("privacy-policy.md"))};\n\n` +
  `export const TERMS_OF_SERVICE_MD = ${JSON.stringify(read("terms-of-service.md"))};\n`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log("wrote", path.relative(process.cwd(), out));
